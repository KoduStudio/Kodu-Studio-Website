#!/usr/bin/env node
/*  Kodu Studio — copy build  (runs anywhere; no npm packages)
    Pulls the page copy out of Sanity and writes it into the site:
      about.html, approach.html, privacy.html   between the <!-- copy:… --> markers
      every mailto: href                        kept in step with the contact email
      site.js                                   the shared details main.js needs
    Run with:  node scripts/build.js   (or on Vercel, npm run build)                 */

const fs = require('fs');
const path = require('path');
const { fetchContent } = require('./sanity.js');
const { injectCopy } = require('./copy.js');

const ROOT = path.resolve(__dirname, '..');
const log = (...a) => console.log(...a);

// Every page carries a plain mailto: as the no-JS fallback for the contact panel.
// Rewriting the href rather than marking it keeps one source of truth without
// caring what the address used to be.
const MAILTO_FILES = ['index.html', 'about.html', 'approach.html', 'privacy.html', 'scripts/templates/project.html'];

function syncMailto(email) {
  let changed = 0;
  for (const rel of MAILTO_FILES) {
    const file = path.join(ROOT, rel);
    const html = fs.readFileSync(file, 'utf8');
    const next = html.replace(/href="mailto:[^"]*"/g, `href="mailto:${email}"`);
    if (next !== html) { fs.writeFileSync(file, next); changed++; }
  }
  return changed;
}

function writeSiteJs(settings) {
  const js = `/* GENERATED by scripts/build.js from Sanity — do not edit by hand.
   To change any of this, edit Site settings in the Studio: https://kodustudio.sanity.studio */
window.KODU_SITE = ${JSON.stringify({
    email: settings.email,
    contactHeading: settings.contactHeading,
    contactIntro: settings.contactIntro,
    socialLinks: (settings.socialLinks || []).map(({ label, url }) => ({ label, url })),
  }, null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, 'site.js'), js);
}

async function run() {
  const { content, source } = await fetchContent();
  const blocks = injectCopy(content);
  const files = syncMailto(content.settings.email);
  writeSiteJs(content.settings);
  log(`\n✓ Copy from ${source}: ${blocks} block(s) written, ${files} mailto file(s) updated, site.js written.`);
}

// Exported so scripts/build.js can wait for it: this step is the only async one, and
// running it to completion before the pages are written keeps the build order honest.
module.exports = { run };

if (require.main === module) {
  run().catch((err) => {
    console.error('\n✗ Copy build failed:', err.message);
    process.exit(1);
  });
}
